"""Default basic auth at the edge, and the one policy file that says so (ticket 292).

`weedr module add gate-traefik` generates the policy: `/etc/guarden/edge/basicauth-policy`
exists, root-owned, in the same directory as the auth-authelia marker
(`edgeconf.MARKER`, spec 6.4) and is generated by the same act — a module
install, never a manifest, never a later sync. From that moment every **new**
service that declares `routes:` carries a basic-auth credential of its own and
its routes are served behind a `basicAuth` middleware; a service created before
the marker exists is grandfathered, because the registry records nothing for it
and no record means no middleware (spec 3.4: the registry is the record).

The credential is the existing machinery end to end (spec 6.2): a minted value
encrypted into `/etc/guarden/creds/<service>/GUARDEN_BASICAUTH.cred` by
`credentials.plant`, re-materialised by the materialiser like any other blob.
The edge reads no secret: what it reads is the htpasswd entry, a root-side
*output* of the mutator — `0640 root:edge` in `/var/lib/guarden/edge/basicauth/`,
which the shipped edge unit mounts read-only at `/etc/guarden/basicauth`. The
directory sits beside `dynamic/` rather than under `/etc/guarden/edge` for one
measured reason: the bind source has to be traversable by the edge's own uid,
and `/etc/guarden/edge` is `0750 root:guarden` (the auth-provider marker's own
directory rule) — a path that uid cannot enter is a container that fails to
start, which is exactly how this was found (t50-slice: `systemctl start` exit 1).
The `edge` group is what the edge's own user holds (`GroupAdd=keep-groups`,
ADR-0017), so the file is readable by the container and by nobody else.

The hash is `{SHA}` — base64 of SHA-1 — which traefik's BasicAuth middleware
documents as an accepted htpasswd format, and the input it protects is a
32-byte `secrets.token_urlsafe` mint, not a passphrase: no dictionary reaches
it, so an unkeyed SHA-1 costs an attacker nothing they can use.

Nothing here reads a manifest, and no key of one reaches this middleware: the
flag travels registry -> renderer -> slice -> `roots`, and a manifest that
wants no auth has nowhere to say so (spec 4's closed key sets, spec 10).
"""

from __future__ import annotations

import base64
import hashlib
import os
from pathlib import Path

from guarden import conf, credentials, errors, paths, registry, users

# The schema key the minted login is planted under, and the name of the record
# in the registry's [generated] table — the same "guarden minted this" ledger a
# poke's values use (spec 3.4).
KEY = "GUARDEN_BASICAUTH"

# The policy marker. Its existence is the whole of the policy: `in_force()` is
# asked at creation time, never at render time, so removing the marker never
# surprises a running fleet with auth it was created without.
POLICY = paths.ETC_GUARDEN / "edge" / "basicauth-policy"
POLICY_MODE = 0o640
POLICY_BODY = "required\n"

# The host directory the edge unit mounts. It exists before any unit mounts it:
# `soil install` converges it, and `weedr module add gate-traefik` creates it
# before the module's own unit is installed. `0755 root:root` — the
# directory must be traversable by the edge user (the *files* inside carry the
# `0640 root:edge` restriction), and it sits beside `dynamic/` under
# `/var/lib/guarden/edge` precisely because that parent is one the edge's uid
# can enter, while `/etc/guarden/edge` is `0750 root:guarden` and is not.
HTPASSWD_DIR = paths.LIB / "edge" / "basicauth"
HTPASSWD_DIR_MODE = 0o755
HTPASSWD_MODE = 0o640

# The path as the edge **container** sees it: the shipped unit mounts the host
# directory here, and `usersFile` is written against the container's own
# filesystem like every other path in the file provider's configuration.
MOUNT = "/etc/guarden/basicauth"


def users_file(service: str) -> str:
    return f"{MOUNT}/{service}.htpasswd"


def host_file(service: str) -> Path:
    return HTPASSWD_DIR / f"{service}.htpasswd"


def _edge_group() -> int | None:
    """The edge group's gid, or `None` on a host that has never had an edge.

    The policy marker is written by the same `module add` that creates the
    group, but `soil install` converges the directory on hosts where no module
    has ever been added, so the soft answer — directory readable, files written
    once the group exists — is the one that keeps both hosts converging.
    """
    try:
        return users.group_id("edge")
    except (KeyError, LookupError):
        return None


def ensure_directory() -> None:
    """`/var/lib/guarden/edge/basicauth`, `0755 root:root`.

    Called from `weedr module add gate-traefik`, which creates it before the
    module's own unit is installed, and from `soil install`, which converges it
    on a host that has never had a module: the shipped edge unit mounts this
    path, and a bind source that does not exist is podman's mkdir — which an
    unprivileged edge user cannot perform under a root-owned parent, so the
    unit would fail to start rather than degrade. The parent directory is
    created with the same default the edge's own `dynamic` directory has always
    been created with; this function states the mode of the directory it
    creates and touches nothing it does not own.
    """
    HTPASSWD_DIR.mkdir(parents=True, exist_ok=True)
    os.chmod(HTPASSWD_DIR, HTPASSWD_DIR_MODE)


def write_policy() -> str:
    """Generate the policy marker. `weedr module add gate-traefik`'s act.

    Written beside the auth-provider marker and with its owner shape
    (`edgeconf.write_marker`): `0640 root:guarden`, in a directory the
    unprivileged programs read through the `guarden` group — an operator and
    `weedr service list` should be able to see the policy exists, and
    `in_force()` is asked root-side at creation.
    """
    conf.write_file(POLICY, POLICY_BODY, POLICY_MODE, (0, users.group_id("guarden")))
    return str(POLICY)


def drop_policy() -> None:
    """Remove the policy marker and its htpasswd entries: `weedr module remove
    gate-traefik`. Existing records keep their flag — a removed module leaves
    no edge to serve them — and `restore` puts a flagged service's entry back
    from its own blob when the module is re-added, so a login an operator holds
    keeps working and a service that no longer exists has no record to restore
    it for."""
    POLICY.unlink(missing_ok=True)
    if HTPASSWD_DIR.is_dir():
        for path in HTPASSWD_DIR.glob("*.htpasswd"):
            path.unlink(missing_ok=True)


def in_force() -> bool:
    """Whether the default applies to a service created right now."""
    return POLICY.is_file()


def digest(password: str) -> str:
    """The htpasswd entry's hash: `{SHA}` + base64(SHA-1(password))."""
    sha = hashlib.sha1(password.encode("utf-8")).digest()
    return "{SHA}" + base64.b64encode(sha).decode("ascii")


def write_entry(service: str, password: str) -> Path:
    """The service's htpasswd line, root-side, `0640 root:edge`."""
    ensure_directory()
    gid = _edge_group()
    owner = (0, gid) if gid is not None else (0, 0)
    path = host_file(service)
    conf.write_file(path, f"{service}:{digest(password)}\n", HTPASSWD_MODE, owner)
    return path


def mint(record, when: str) -> None:
    """Plant the service's login, carry it into the service's own store, and
    record both halves.

    Idempotent by the record: the first mint is the login, and a re-ingest or
    an instance of an already-flagged service never re-mints — a login that
    changed underneath an operator's stored credential would be worse than no
    credential at all. **It also never re-asks**, so the ask below is paid once
    per service and not on every converge.

    **The plant asks the materialiser to run, and the order of these three
    lines is the whole of the reason.** `credentials.plant` writes the
    encrypted blob; the value is in the service's own podman store only once
    the materialiser has decrypted it there, and the store is what the
    container's `Secret=` line resolves against. So a plant that does not ask
    leaves the value's arrival to whoever notices the blob — and the only
    thing that notices it is the `guarden-creds.path` watcher, which fires
    when it fires.

    **Measured, because "the watcher is usually fast enough" is not a
    guarantee.** With the watcher running, the value was in the store before
    the ingest returned — the watcher fires on the blob's own write while the
    mutator is still working, so the timing won the race. With
    `guarden-creds.path` stopped, the value NEVER arrived: not immediately,
    not after fifteen seconds, and only when `guarden-creds-boot.service` was
    started by hand. So the watcher's arrival is a timing win and not a
    delivery guarantee, and a box whose path unit is not running — a
    converged host that has not been rebooted since it was installed, a host
    where the unit failed, a host where somebody stopped it — carried a blob
    and no store copy until the next boot.

    **So the mint asks, the way every other plant asks.** `weedr secret set`
    plants and then asks (spec 6.2: "encrypts into
    `/etc/guarden/creds/<name>/<KEY>.cred` mode `0600`, then asks the
    credential materialiser to run"), and the interactive creator plants and
    asks. A mint is a plant of a credential, and the spec's rule is about the
    plant rather than about the verb that performed it.

    **The ask is BEFORE the htpasswd entry, and the reason is what a failure
    leaves behind.** The ask raises when the materialiser is installed and
    could not carry the value, and this is the root-side mutator: raising
    ends the creation before the record is saved, so a service that was never
    created leaves no htpasswd entry pointing at a login nothing serves.
    Writing the entry first would leave exactly that: an orphan file for a
    service the registry never recorded.

    **And the ask is before the record's own flags for the same reason**: a
    failed ask must not record a login as minted, because the next attempt
    mints a fresh value and a half-recorded one would look like the first
    mint had happened.

    **The ask is the documented no-op on a host that has not converged.** A
    box whose `soil install` has not run has no materialiser unit at all, and
    `ask_materialiser` warns and returns for that case rather than raising —
    so a service created on such a box still holds its blob and its htpasswd
    entry, and the value reaches the store when the phase that owns the unit
    has run. That is the same contract the other two callers of the ask get.
    """
    if record.basicauth:
        return
    password = credentials.generated_value()
    blob = credentials.plant(record.service, KEY, password)
    credentials.ask_materialiser(record.service, KEY, blob)
    write_entry(record.service, password)
    record.basicauth = True
    record.generated[KEY] = when


def owns(service: str, key: str) -> bool:
    """Whether this module's credential is the one being written.

    The predicate is the KEY and the record's flag, and nothing else. A
    service that never carried a login has no entry to rewrite, and a key
    that is not this module's is not this module's business — the credential
    module asks every owner it knows, and each one answers for itself.

    **A record that cannot be read is not this module's business either.**
    The registry is the record of the fact, and a registry that will not
    parse is the host not being in the state the request assumed — but it is
    a fact about the RECORD, and this function is asked a question about the
    credential. The verb that owns the record reports that failure itself,
    with the path in the message; here the answer is "not mine", and the
    credential is written exactly as it would be for any other key.
    """
    if key != KEY:
        return False
    try:
        record = registry.load(service)
    except errors.GuardenError:
        return False
    return record is not None and record.basicauth


def rotate(service: str, key: str, stored: str) -> bool:
    """Rewrite the service's htpasswd entry from a value that was just planted.

    **The edge does not read the blob — it reads the entry.** So a rotation
    that replaces the blob and leaves the entry alone puts a login in front of
    the edge that is not the one the operator just rotated to, and the two
    halves of one credential disagree until somebody rewrites the entry by
    hand. This is the hook that stops that: the same act that replaces the
    blob re-derives the entry from the same value.

    The shape is `restore`'s — write the entry from a value — and the
    difference is only where the value comes from: `restore` reads it back
    out of the blob, because the blob is all it has; this one is handed the
    value that was just planted, so the entry and the blob are derived from
    ONE value rather than from two reads of one file.

    **A service that never carried a login is not this function's business.**
    The flag is the record of the fact, and a service created before the
    policy has no entry and no middleware — so there is nothing to rewrite
    and nothing to report.

    **A write that cannot be made is a diagnostic, not a traceback.** The
    entry is root-side state on a filesystem that can refuse even root, and
    the refusal is the host not being in the state the request assumed — so
    it is one line naming the service and the path, and the caller is the
    one that decides what a refusal means for the credential as a whole.
    """
    if not owns(service, key):
        return False
    path = host_file(service)
    try:
        write_entry(service, stored)
    except OSError as exc:
        raise errors.GuardenError(
            f"the basic-auth entry of {service} could not be written at {path}: "
            f"{exc.strerror or exc}",
            errors.HOST_NOT_AS_ASSUMED,
        ) from None
    return True


def restore(record) -> bool:
    """Rewrite a flagged service's htpasswd entry from its own minted blob.

    `weedr module remove gate-traefik` drops every entry with the policy
    (`drop_policy`) while each service's registry keeps its flag, and `roots`
    attaches the `usersFile` middleware to a flagged service whether or not the
    file is there — so re-adding the module has to put the entries back, or
    every flagged service is a login nobody can use with nothing reporting it.
    The password is the one already minted: the blob was never dropped, so an
    operator's stored credential keeps working and nothing is re-minted.
    True when an entry was written; a service that is not flagged, or whose
    entry is already in place, is not this function's business and answers
    False.
    """
    if not record.basicauth or host_file(record.service).is_file():
        return False
    password = credentials.value(record.service, KEY)
    if password is None:
        return False
    write_entry(record.service, password)
    return True


def drop(service: str) -> None:
    """A removed service takes its htpasswd entry with it."""
    host_file(service).unlink(missing_ok=True)
